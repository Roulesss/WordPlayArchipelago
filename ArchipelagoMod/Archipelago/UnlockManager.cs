        public static void ResetState()
        {
            LockModifiers = false;
            LockTileChanges = false;
            LockTileAdditions = false;
            UnlockedBonuses.Clear();
            PlaceholderShopSlots.Clear();
            Plugin.Logger?.LogInfo("[UnlockManager] State reset.");
        }

        public static void RegisterUnlock(long itemId)
        {
            if (ItemIdToGameName.TryGetValue(itemId, out string gameName))
            {
                RegisterUnlock(gameName);
            }
        }

        public static void RegisterUnlock(string gameName)
        {
            if (string.IsNullOrEmpty(gameName)) return;
            if (UnlockedBonuses.Add(gameName))
            {
                string disp = GameNameToItemName.TryGetValue(gameName, out var d) ? d : gameName;
                Plugin.Logger?.LogInfo($"[UnlockManager] Unlocked perk: {disp} ({gameName})!");
            }
        }

        public static bool IsBonusUnlocked(BaseBonus bonus)
        {
            if (bonus == null) return false;
            string name = bonus.gameObject != null ? bonus.gameObject.name : null;
            if (string.IsNullOrEmpty(name)) return false;

            switch (bonus.BonusType)
            {
                case BaseBonus.Type.Modifier:
                    if (!LockModifiers) return true;
                    return UnlockedBonuses.Contains(name);

                case BaseBonus.Type.Upgrade:
                    if (!LockTileChanges) return true;
                    return UnlockedBonuses.Contains(name);

                case BaseBonus.Type.Gift:
                    if (!LockTileAdditions) return true;
                    return UnlockedBonuses.Contains(name);

                default:
                    return true;
            }
        }
